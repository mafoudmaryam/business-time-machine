/** Plain-language explanation of the band-plus-line charts, for owners who
 * have never seen a range band before. */
export function ChartCaption() {
  return (
    <p className="chart-caption">
      Each line is the most likely outcome. The shaded band around it shows where 8 of 10 simulated futures land,
      from bad case to good case. "M6" means month 6 from now.
    </p>
  );
}
